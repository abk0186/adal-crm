-- ---------- Команда и доступ ----------
-- allowlist: email, которым разрешён вход в CRM. Заполняет только админ через SQL.
create table if not exists crm.allowlist (
  email text primary key check (email = lower(email)),
  full_name text,
  role text not null default 'manager' check (role in ('admin','manager')),
  added_at timestamptz not null default now()
);

create table if not exists crm.team_members (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  full_name text,
  role text not null default 'manager' check (role in ('admin','manager')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Telegram chat_id для будущих напоминаний (бот пока НЕ создан)
create table if not exists crm.telegram_chats (
  user_id uuid primary key references crm.team_members(user_id) on delete cascade,
  chat_id bigint not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function crm.is_member() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from crm.team_members m where m.user_id = auth.uid() and m.active);
$$;
create or replace function crm.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from crm.team_members m where m.user_id = auth.uid() and m.active and m.role = 'admin');
$$;
revoke all on function crm.is_member(), crm.is_admin() from public, anon;
grant execute on function crm.is_member(), crm.is_admin() to authenticated, service_role;

-- Новый пользователь Auth с email из allowlist автоматически становится членом команды
create or replace function crm.on_auth_user_created() returns trigger
language plpgsql security definer set search_path = '' as $$
declare a crm.allowlist;
begin
  select * into a from crm.allowlist where email = lower(new.email);
  if found then
    insert into crm.team_members(user_id, email, full_name, role)
    values (new.id, lower(new.email), a.full_name, a.role)
    on conflict (user_id) do nothing;
  end if;
  return new;
end $$;
revoke all on function crm.on_auth_user_created() from public, anon, authenticated;
drop trigger if exists crm_on_auth_user_created on auth.users;
create trigger crm_on_auth_user_created after insert on auth.users
  for each row execute function crm.on_auth_user_created();

-- ---------- Телефон ----------
-- Нормализация к +7XXXXXXXXXX (8XXXXXXXXXX, 7XXXXXXXXXX, XXXXXXXXXX, с пробелами/скобками)
create or replace function crm.normalize_phone(p text) returns text
language plpgsql immutable set search_path = '' as $$
declare d text := regexp_replace(coalesce(p,''), '\D', '', 'g');
begin
  if length(d) = 11 and left(d,1) in ('7','8') then return '+7' || right(d,10);
  elsif length(d) = 10 then return '+7' || d;
  else return null; end if;
end $$;

-- ---------- Основные таблицы ----------
create table if not exists crm.contacts (
  id uuid primary key default gen_random_uuid(),
  phone text not null unique check (phone ~ '^\+7[0-9]{10}$'),
  name text,
  city text,
  notes text,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists crm.deals (
  id uuid primary key default gen_random_uuid(),
  contact_id uuid not null references crm.contacts(id) on delete cascade,
  direction_id smallint not null default 1 references crm.directions(id),
  product text default 'ADAL MODEL 907',
  stage crm.deal_stage not null default 'Новая заявка',
  source crm.lead_source not null default 'Другое',
  responsible uuid default auth.uid() references crm.team_members(user_id) on delete set null,
  city text,
  quantity integer default 1 check (quantity is null or quantity >= 0),
  amount numeric(14,2) check (amount is null or amount >= 0),       -- ₸
  payment_terms text,
  purpose text,          -- для чего нужна техника
  deadline text,         -- срок
  budget text,
  decision_maker text,   -- кто решает
  comments text,
  lost_reason text,
  stage_changed_at timestamptz not null default now(),
  closed_at timestamptz,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint deals_lost_reason_required check (stage <> 'Отказ' or nullif(btrim(lost_reason),'') is not null)
);
create index if not exists deals_contact_idx on crm.deals(contact_id);
create index if not exists deals_stage_idx on crm.deals(stage);

create table if not exists crm.touches (
  id uuid primary key default gen_random_uuid(),
  contact_id uuid not null references crm.contacts(id) on delete cascade,
  deal_id uuid references crm.deals(id) on delete cascade,
  kind crm.touch_kind not null default 'note',
  body text,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists touches_deal_idx on crm.touches(deal_id, created_at desc);
create index if not exists touches_contact_idx on crm.touches(contact_id, created_at desc);

create table if not exists crm.tasks (
  id uuid primary key default gen_random_uuid(),
  deal_id uuid not null references crm.deals(id) on delete cascade,
  title text not null,
  due_at timestamptz not null default now(),
  done boolean not null default false,
  done_at timestamptz,
  assignee uuid default auth.uid() references crm.team_members(user_id) on delete set null,
  auto boolean not null default false,
  reminded_at timestamptz,   -- для будущих Telegram-напоминаний
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists tasks_open_idx on crm.tasks(done, due_at);
create index if not exists tasks_deal_idx on crm.tasks(deal_id);

-- ---------- Триггеры ----------
create or replace function crm.tg_contacts_before() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.phone := coalesce(crm.normalize_phone(new.phone), new.phone);
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists contacts_before on crm.contacts;
create trigger contacts_before before insert or update on crm.contacts
  for each row execute function crm.tg_contacts_before();

-- конец текущего дня по Алматы
create or replace function crm.end_of_today() returns timestamptz
language sql stable set search_path = '' as $$
  select (date_trunc('day', now() at time zone 'Asia/Almaty') + interval '23 hours 59 minutes') at time zone 'Asia/Almaty';
$$;

create or replace function crm.tg_deals_before() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  if tg_op = 'INSERT' or new.stage is distinct from old.stage then
    new.stage_changed_at := now();
    new.closed_at := case when new.stage in ('Успешно','Отказ') then now() else null end;
  end if;
  return new;
end $$;
drop trigger if exists deals_before on crm.deals;
create trigger deals_before before insert or update on crm.deals
  for each row execute function crm.tg_deals_before();

create or replace function crm.tg_deals_after() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    insert into crm.tasks(deal_id, title, due_at, assignee, auto, created_by)
    values (new.id, 'Связаться', crm.end_of_today(), new.responsible, true, new.created_by);
  elsif new.stage is distinct from old.stage then
    insert into crm.touches(contact_id, deal_id, kind, body, created_by)
    values (new.contact_id, new.id, 'system',
            'Этап: ' || old.stage || ' → ' || new.stage ||
            case when new.stage = 'Отказ' then ' (причина: ' || new.lost_reason || ')' else '' end,
            auth.uid());
    if new.stage = 'КП отправлено' then
      insert into crm.tasks(deal_id, title, due_at, assignee, auto, created_by)
      values (new.id, 'Переспросить по КП', now() + interval '2 days', new.responsible, true, auth.uid());
    elsif new.stage = 'Счёт/договор' then
      insert into crm.tasks(deal_id, title, due_at, assignee, auto, created_by)
      values (new.id, 'Проверить оплату', now() + interval '3 days', new.responsible, true, auth.uid());
    end if;
  end if;
  return null;
end $$;
revoke all on function crm.tg_deals_after() from public, anon, authenticated;
drop trigger if exists deals_after on crm.deals;
create trigger deals_after after insert or update of stage on crm.deals
  for each row execute function crm.tg_deals_after();

create or replace function crm.tg_tasks_before() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.done and (tg_op = 'INSERT' or not old.done) then new.done_at := now();
  elsif not new.done then new.done_at := null; end if;
  return new;
end $$;
drop trigger if exists tasks_before on crm.tasks;
create trigger tasks_before before insert or update on crm.tasks
  for each row execute function crm.tg_tasks_before();

-- ---------- Дедуп лида (общая логика) ----------
-- Есть контакт с таким телефоном → используем его; есть открытая сделка → добавляем касание в неё;
-- иначе создаём сделку «Новая заявка». Возвращает jsonb.
create or replace function crm._upsert_lead(
  p_phone text, p_name text, p_source crm.lead_source, p_text text,
  p_actor uuid, p_direction smallint default 1, p_city text default null
) returns jsonb
language plpgsql set search_path = '' as $$
declare
  v_phone text := crm.normalize_phone(p_phone);
  v_contact crm.contacts;
  v_deal_id uuid;
  v_new_contact boolean := false;
  v_new_deal boolean := false;
  v_kind crm.touch_kind := case p_source when 'WhatsApp' then 'whatsapp' when 'SMS' then 'sms'
                                         when 'Реклама-звонок' then 'call' else 'note' end;
begin
  if v_phone is null then raise exception 'Неверный номер телефона: %', p_phone using errcode = '22023'; end if;
  select * into v_contact from crm.contacts where phone = v_phone;
  if not found then
    insert into crm.contacts(phone, name, city, created_by)
    values (v_phone, nullif(btrim(p_name),''), nullif(btrim(p_city),''), p_actor)
    returning * into v_contact;
    v_new_contact := true;
  else
    if v_contact.name is null and nullif(btrim(p_name),'') is not null then
      update crm.contacts set name = btrim(p_name) where id = v_contact.id;
    end if;
  end if;

  select id into v_deal_id from crm.deals
   where contact_id = v_contact.id and stage not in ('Успешно','Отказ')
     and direction_id = coalesce(p_direction, 1)
   order by created_at desc limit 1;

  if v_deal_id is null then
    insert into crm.deals(contact_id, direction_id, source, responsible, city, created_by)
    values (v_contact.id, coalesce(p_direction,1), coalesce(p_source,'Другое'),
            case when exists (select 1 from crm.team_members where user_id = p_actor) then p_actor end,
            coalesce(nullif(btrim(p_city),''), v_contact.city), p_actor)
    returning id into v_deal_id;
    v_new_deal := true;
  end if;

  insert into crm.touches(contact_id, deal_id, kind, body, created_by)
  values (v_contact.id, v_deal_id, v_kind,
          case when v_new_deal then 'Новая заявка (' || coalesce(p_source::text,'Другое') || ')'
               else 'Повторное обращение (' || coalesce(p_source::text,'Другое') || ')' end
          || coalesce(': ' || nullif(btrim(p_text),''), ''),
          p_actor);

  return jsonb_build_object('contact_id', v_contact.id, 'deal_id', v_deal_id, 'phone', v_phone,
                            'new_contact', v_new_contact, 'new_deal', v_new_deal);
end $$;
revoke all on function crm._upsert_lead(text,text,crm.lead_source,text,uuid,smallint,text) from public, anon, authenticated;

-- Для будущей WhatsApp-рутины: только service_role / SQL-админ (не через anon/authenticated)
create or replace function crm.ingest_lead(phone text, name text, source text, text text)
returns jsonb language plpgsql security definer set search_path = '' as $$
begin
  return crm._upsert_lead(phone, name, coalesce(nullif(source,''),'Другое')::crm.lead_source, text, null::uuid, 1::smallint, null::text);
end $$;
revoke all on function crm.ingest_lead(text,text,text,text) from public, anon, authenticated;
grant execute on function crm.ingest_lead(text,text,text,text) to service_role;

