-- ADAL CRM v1 — схема crm (Supabase project iwpmrordpxrkxlpaxutx)
-- Данные лежат в схеме crm (не выставлена в Data API).
-- Браузер работает через тонкие view public.crm_* (security_invoker) и RPC public.crm_*,
-- поэтому RLS таблиц crm действует всегда. anon не имеет доступа ни к чему.

create schema if not exists crm;
revoke all on schema crm from public, anon;
grant usage on schema crm to authenticated, service_role;

-- ---------- Справочники ----------
do $$ begin
  create type crm.deal_stage as enum ('Новая заявка','Связались','Квалификация','КП отправлено','Счёт/договор','Оплата','Отгрузка','Успешно','Отказ');
exception when duplicate_object then null; end $$;
do $$ begin
  create type crm.lead_source as enum ('Реклама-звонок','WhatsApp','SMS','Сайт','Рекомендация','Другое');
exception when duplicate_object then null; end $$;
do $$ begin
  create type crm.touch_kind as enum ('call','whatsapp','sms','meeting','note','system');
exception when duplicate_object then null; end $$;

