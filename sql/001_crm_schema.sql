drop policy if exists tg_own on crm.telegram_chats;
create policy tg_own on crm.telegram_chats for all to authenticated
  using (crm.is_member() and (user_id = auth.uid() or crm.is_admin()))
  with check (crm.is_member() and (user_id = auth.uid() or crm.is_admin()));
-- allowlist: политик нет → только админ через SQL

do $$ declare t text; begin
  foreach t in array array['contacts','deals','touches','tasks'] loop
    execute format('drop policy if exists %1$s_sel on crm.%1$s', t);
    execute format('drop policy if exists %1$s_ins on crm.%1$s', t);
    execute format('drop policy if exists %1$s_upd on crm.%1$s', t);
    execute format('drop policy if exists %1$s_del on crm.%1$s', t);
    execute format('create policy %1$s_sel on crm.%1$s for select to authenticated using (crm.is_member())', t);
    execute format('create policy %1$s_ins on crm.%1$s for insert to authenticated with check (crm.is_member())', t);
    execute format('create policy %1$s_upd on crm.%1$s for update to authenticated using (crm.is_member()) with check (crm.is_member())', t);
  end loop;
end $$;
-- удалять сделки/контакты может только админ; задачи и касания — любой член команды
